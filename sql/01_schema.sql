DROP TABLE IF EXISTS order_item CASCADE;
DROP TABLE IF EXISTS customer_order CASCADE;
DROP TABLE IF EXISTS product CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;
DROP TABLE IF EXISTS pickup_point CASCADE;
DROP TABLE IF EXISTS order_status CASCADE;
DROP TABLE IF EXISTS unit CASCADE;
DROP TABLE IF EXISTS supplier CASCADE;
DROP TABLE IF EXISTS manufacturer CASCADE;
DROP TABLE IF EXISTS category CASCADE;
DROP TABLE IF EXISTS user_role CASCADE;

CREATE TABLE user_role (
    user_role_id integer GENERATED BY DEFAULT AS IDENTITY,
    role_name varchar(50) NOT NULL,
    CONSTRAINT pk_user_role PRIMARY KEY (user_role_id),
    CONSTRAINT uq_user_role_name UNIQUE (role_name)
);

CREATE TABLE category (
    category_id integer GENERATED BY DEFAULT AS IDENTITY,
    category_name varchar(100) NOT NULL,
    CONSTRAINT pk_category PRIMARY KEY (category_id),
    CONSTRAINT uq_category_name UNIQUE (category_name)
);

CREATE TABLE manufacturer (
    manufacturer_id integer GENERATED BY DEFAULT AS IDENTITY,
    manufacturer_name varchar(100) NOT NULL,
    CONSTRAINT pk_manufacturer PRIMARY KEY (manufacturer_id),
    CONSTRAINT uq_manufacturer_name UNIQUE (manufacturer_name)
);

CREATE TABLE supplier (
    supplier_id integer GENERATED BY DEFAULT AS IDENTITY,
    supplier_name varchar(100) NOT NULL,
    CONSTRAINT pk_supplier PRIMARY KEY (supplier_id),
    CONSTRAINT uq_supplier_name UNIQUE (supplier_name)
);

CREATE TABLE unit (
    unit_id integer GENERATED BY DEFAULT AS IDENTITY,
    unit_name varchar(20) NOT NULL,
    CONSTRAINT pk_unit PRIMARY KEY (unit_id),
    CONSTRAINT uq_unit_name UNIQUE (unit_name)
);

CREATE TABLE order_status (
    order_status_id integer GENERATED BY DEFAULT AS IDENTITY,
    status_name varchar(50) NOT NULL,
    CONSTRAINT pk_order_status PRIMARY KEY (order_status_id),
    CONSTRAINT uq_order_status_name UNIQUE (status_name)
);

CREATE TABLE pickup_point (
    pickup_point_id integer GENERATED BY DEFAULT AS IDENTITY,
    address varchar(255) NOT NULL,
    CONSTRAINT pk_pickup_point PRIMARY KEY (pickup_point_id),
    CONSTRAINT uq_pickup_point_address UNIQUE (address)
);

CREATE TABLE app_user (
    user_id integer GENERATED BY DEFAULT AS IDENTITY,
    user_role_id integer NOT NULL,
    last_name varchar(50) NOT NULL,
    first_name varchar(50) NOT NULL,
    patronymic varchar(50),
    login varchar(100) NOT NULL,
    password varchar(100) NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_login UNIQUE (login),
    CONSTRAINT fk_app_user_role FOREIGN KEY (user_role_id)
        REFERENCES user_role (user_role_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE product (
    product_id integer GENERATED BY DEFAULT AS IDENTITY,
    article varchar(20) NOT NULL,
    product_name varchar(100) NOT NULL,
    category_id integer NOT NULL,
    manufacturer_id integer NOT NULL,
    supplier_id integer NOT NULL,
    unit_id integer NOT NULL,
    price numeric(10,2) NOT NULL,
    discount smallint NOT NULL DEFAULT 0,
    stock_quantity integer NOT NULL DEFAULT 0,
    description text,
    photo_path varchar(255),
    CONSTRAINT pk_product PRIMARY KEY (product_id),
    CONSTRAINT uq_product_article UNIQUE (article),
    CONSTRAINT ck_product_price CHECK (price >= 0),
    CONSTRAINT ck_product_discount CHECK (discount BETWEEN 0 AND 100),
    CONSTRAINT ck_product_stock CHECK (stock_quantity >= 0),
    CONSTRAINT fk_product_category FOREIGN KEY (category_id)
        REFERENCES category (category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_product_manufacturer FOREIGN KEY (manufacturer_id)
        REFERENCES manufacturer (manufacturer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_product_supplier FOREIGN KEY (supplier_id)
        REFERENCES supplier (supplier_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_product_unit FOREIGN KEY (unit_id)
        REFERENCES unit (unit_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE customer_order (
    order_id integer GENERATED BY DEFAULT AS IDENTITY,
    order_date date NOT NULL,
    delivery_date date NOT NULL,
    pickup_point_id integer NOT NULL,
    user_id integer NOT NULL,
    receive_code integer NOT NULL,
    order_status_id integer NOT NULL,
    CONSTRAINT pk_customer_order PRIMARY KEY (order_id),
    CONSTRAINT ck_order_dates CHECK (delivery_date >= order_date),
    CONSTRAINT fk_order_pickup_point FOREIGN KEY (pickup_point_id)
        REFERENCES pickup_point (pickup_point_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_order_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_order_status FOREIGN KEY (order_status_id)
        REFERENCES order_status (order_status_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE order_item (
    order_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL,
    CONSTRAINT pk_order_item PRIMARY KEY (order_id, product_id),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id)
        REFERENCES customer_order (order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id)
        REFERENCES product (product_id) ON UPDATE CASCADE ON DELETE RESTRICT
);